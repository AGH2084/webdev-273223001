test('AC-24 AC-2 AC-3 AC-4 AC-5 AC-6 AC-9 AC-19 PostgreSQL migrations, real HTTP/MCP and competing registrations preserve integrity', { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const schema = 'test_' + randomUUID().replaceAll('-', '');
  const admin = openPostgres(process.env.TEST_DATABASE_URL);
  await admin.pool.query(`CREATE SCHEMA ${schema}`);
  const db = openPostgres(process.env.TEST_DATABASE_URL, { options: `-c search_path=${schema}` });
  t.after(async () => { await db.close(); await admin.pool.query(`DROP SCHEMA ${schema} CASCADE`); await admin.close(); });
  await migratePostgres(db); await migratePostgres(db);
  const query = (sql, args) => db.pool.query(sql, args);
  assert.equal((await query('SELECT * FROM schema_migrations')).rowCount, 2);
  const password = 'disposable-postgres-test-password';
  await query("INSERT INTO users (id,email,name,password_hash,role) VALUES (1,'member@example.test','Member',$1,'member'),(2,'organiser@example.test','Organiser',$1,'organiser'),(3,'other@example.test','Other',$1,'member')", [await hashPassword(password)]);
  await query("SELECT setval(pg_get_serial_sequence('users','id'),3)");
  await query("INSERT INTO clubs (id,name,owner_id) VALUES (1,'Club',2)");
  await query("INSERT INTO events (id,club_id,owner_id,title,description,starts_at,venue,capacity) VALUES (1,1,2,'One place','Description','2099-01-01T12:00:00.000Z','Lab',1)");
  await query("SELECT setval(pg_get_serial_sequence('events','id'),1)");
  const data = repository(db); const auth = authService(data);
  const member = await auth.login('MEMBER@example.test', password); const owner = await auth.login('organiser@example.test', password); const other = await auth.login('other@example.test', password);
  const registrations = registrationsService(data, auth);
  const attempts = await Promise.allSettled([registrations.register(member.token, 1), registrations.register(other.token, 1)]);
  assert.equal(attempts.filter(r => r.status === 'fulfilled').length, 1);
  assert.equal(attempts.find(r => r.status === 'rejected').reason.code, 'EventFull');
  const winner = attempts.find(r => r.status === 'fulfilled').value;
  const winningToken = winner.userId === 1 ? member.token : other.token;
  await assert.rejects(registrations.register(winningToken, 1), { code: 'AlreadyRegistered' });
  await assert.rejects(registrations.cancel(owner.token, winner.id), { code: 'Forbidden' });
  assert.equal((await data.myRegistrations(winner.userId)).length, 1);
  await assert.rejects(query('INSERT INTO registrations (user_id,event_id) VALUES (2,1)'), /event_capacity_exceeded/);
  const management = eventManagement(data, auth);
  const details = { title: 'New event', description: 'Description', venue: 'Room', startsAt: '2099-02-01T12:00:00Z', capacity: 2, clubId: 1 };
  const created = await management.create(owner.token, details);
  await management.edit(owner.token, created.id, { ...details, title: 'Edited' });
  assert.equal((await management.clubs(owner.token)).length, 1);
  assert.equal((await management.detail(owner.token, 1)).attendees.length, 1);
  await registrations.register(member.token, created.id); await registrations.register(other.token, created.id);
  await assert.rejects(query('UPDATE events SET capacity=1 WHERE id=$1', [created.id]), /capacity_below_registrations/);
  await management.remove(owner.token, created.id);
  assert.equal((await query('SELECT * FROM registrations WHERE event_id=$1', [created.id])).rowCount, 0);
  const app = createApp(db, { providerClient: { configured: false }, modelClient: { configured: false } });
  app.listen(0, '127.0.0.1'); await once(app, 'listening');
  t.after(() => new Promise(resolve => app.close(resolve)));
  const base = `http://127.0.0.1:${app.address().port}`;
  assert.equal((await fetch(`${base}/health`)).status, 200);
  const services = { events: eventsService(data, auth), registrations };
  const full = await handle({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'register', arguments: { eventId: 1 } } }, services, owner.token);
  assert.equal(full.result.isError, true); assert.equal(full.result.content[0].text, 'This event is full');
  const refused = await fetch(`${base}/api/registrations`, { method: 'POST', headers: { Cookie: `club_session=${owner.token}`, 'Content-Type': 'application/json' }, body: '{"eventId":1}' });
  assert.equal(refused.status, 409);
  await registrations.cancel(winningToken, winner.id);
  assert.equal((await data.event(1)).registered, 0);
  const profile = { sub: 'pg-google-sub', email: 'member@example.test', email_verified: true };
  const provider = providerAuth(data, auth, { configured: true, authorization: () => 'url', exchange: async () => profile });
  const flow = await provider.begin(); assert.equal((await provider.complete(flow.state, flow.state, 'code')).user.id, 1);
  const again = await provider.begin(); assert.equal((await provider.complete(again.state, again.state, 'code')).user.id, 1);
  profile.sub = 'pg-new-sub'; profile.email = 'new@example.test';
  const fresh = await provider.begin(); assert.equal((await provider.complete(fresh.state, fresh.state, 'code')).user.role, 'member');
  const expired = await provider.begin(); assert.equal(await data.consumeOAuthState(require('../src/services/auth').digest(expired.state), '9999'), null);
  await auth.logout(member.token); await assert.rejects(auth.requireUser(member.token), { code: 'Unauthenticated' });
  assert.equal((await data.upcoming('2000')).length, 1);
});


test('AC-24 AC-11 AC-13 explicit PostgreSQL seeding and password rotation preserve existing events', { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const { seedPostgres, rotatePostgresPassword } = require('../src/data/postgres-seed');
  const schema = 'test_' + randomUUID().replaceAll('-', '');
  const admin = openPostgres(process.env.TEST_DATABASE_URL);
  await admin.pool.query(`CREATE SCHEMA ${schema}`);
  const options = { options: `-c search_path=${schema}` };
  let db = openPostgres(process.env.TEST_DATABASE_URL, options);
  t.after(async () => { await db.close(); await admin.pool.query(`DROP SCHEMA ${schema} CASCADE`); await admin.close(); });
  await migratePostgres(db);
  assert.equal(await seedPostgres(db, await hashPassword('old-test-password')), true);
  assert.equal(await seedPostgres(db, 'unused'), false);
  const auth = authService(repository(db));
  const session = await auth.login('member@example.test', 'old-test-password');
  const data = repository(db); await data.removeEvent(2);
  await rotatePostgresPassword(db, await hashPassword('new-test-password'));
  await assert.rejects(auth.requireUser(session.token), { code: 'Unauthenticated' });
  assert.equal((await auth.login('member@example.test', 'new-test-password')).user.id, 1);
  assert.equal((await db.pool.query('SELECT * FROM events')).rowCount, 3);
  await db.close(); db = openPostgres(process.env.TEST_DATABASE_URL, options);
  assert.equal(await repository(db).event(2), undefined);
  await migratePostgres(db); assert.equal(await seedPostgres(db, 'unused'), false);
  assert.equal(await repository(db).event(2), undefined);
  await db.pool.query('DELETE FROM users WHERE id=1');
  await assert.rejects(rotatePostgresPassword(db, 'unused'), /Both local demo accounts/);
});
